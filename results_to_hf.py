from argparse import ArgumentParser
import os

import numpy as np
import torch
from einops import rearrange

from huggingface_hub import whoami, login
import datasets

def reformat_summary_old(
    summary_dict:dict[tuple, torch.Tensor|dict[str,torch.Tensor]]
    )->dict[str,list[int]|np.ndarray]:
    n_layers, n_neurons = summary_dict['gate+_in+', 'freq'].shape
    new_dict:dict[str,list[int]|np.ndarray] = {
        "layer": [l for l in range(n_layers) for _n in range(n_neurons)],
        "neuron": list(range(n_neurons))*n_layers,
    }
    for key,value in summary_dict.items():
        str_key = "_".join(key).replace("sum", "mean")
        if key[-1]!='max':
            pattern = 'l n -> (l n)' if value.ndim==2 else '1 l n -> (l n)'
            new_dict[str_key] = rearrange(value, pattern).detach().cpu().numpy()
        else:
            new_dict[f'{str_key}_values'] = rearrange(
                value['values'], 'topk l n -> (l n) topk'
            ).detach().cpu().numpy()
            new_dict[f'{str_key}_indices'] = rearrange(
                value['indices'], 'topk l n -> (l n) topk'
            ).detach().cpu().numpy()
    return new_dict

def reformat_summary(
    summary_dict:dict[tuple, torch.Tensor|dict[str,torch.Tensor]]
    )->dict[str,list[int]|np.ndarray]:
    n_layers, n_neurons = summary_dict['gate+_in+', 'freq'].shape
    new_dict:dict[str,list[int]|np.ndarray] = {
        "layer": [l for l in range(n_layers) for _n in range(n_neurons)],
        "neuron": list(range(n_neurons))*n_layers,
    }
    keyset = set()
    for key in summary_dict:
        if key[-1]=='freq':
            keyset.add(key)
        else:
            keyset.add((key[0], '.'.join(key[1].split('.')[2:]), key[2]))
    for key in keyset:
        str_key = "_".join(key).replace("sum", "mean")
        if key[-1]=='freq':
            new_dict[str_key] = rearrange(summary_dict[key], 'l n -> (l n)').detach().cpu().numpy()
        elif key[-1]!='sum':
            new_dict[str_key] = torch.cat(
                summary_dict[(key[0], f'blocks.{layer}.{key[1]}', key[2])]
                for layer in range(n_layers)
            ).detach().cpu().numpy()
        else:
            assert key[-1]=='max', f"last part of key should be 'freq', 'str', or 'max', but key is {key}"
            new_dict[f'{str_key}_values'] = torch.cat(
                rearrange(summary_dict[(key[0], f'blocks.{layer}.{key[1]}', key[2])]['values'], 'topk n -> n topk')
                for layer in range(n_layers)
            ).detach().cpu().numpy()
            new_dict[f'{str_key}_indices'] = torch.cat(
                rearrange(summary_dict[(key[0], f'blocks.{layer}.{key[1]}', key[2])]['indices'], 'topk n -> n topk')
                for layer in range(n_layers)
            ).detach().cpu().numpy()
    return new_dict

def sample_generator(sample_dict:dict[str, list[int]|torch.Tensor]):
    """Generator that can be converted into a huggingface dataset,
    based on a dict of sampled activations

    Args:
        sample_dict (dict[str, list | torch.Tensor]):
            Generated by b_activations.py. Entries are:
            'sampled_positions' (list[int]):
                the position within the sequence where each sampled activation comes from.
                (One activation was sampled from sequence 0, one from sequence 1, etc.)
            'mlp.hook_post', 'mlp.hook_pre', 'mlp.hook_pre_linear' (torch.Tensor):
                Here the shape is (sample, layer, neuron).

    Yields:
        For each layer-neuron pair, a dict[str, list[int]|np.ndarray]:
        Each dict entry corresponds to a column of the future dataset
        Dict keys (columns):
            'layer' (int): layer index
            'neuron' (int): neuron index within layer
            'sampled_positions' (list[int]):
                list of the position indices of the samples within each sequence.
                This is just the same for every neuron.
            'mlp.hook_post', 'mlp.hook_pre', 'mlp.hook_pre_linear' (list[float]):
                The sampled activations (one list item per sample)
    """
    n_samples, n_layers, n_neurons = sample_dict['mlp.hook_post'].shape
    for layer in range(n_layers):
        for neuron in range(n_neurons):
            new_dict:dict[str,int|list[int]|list[float]] = {
                "layer": layer,
                "neuron": neuron,
                "sampled_positions": sample_dict["sampled_positions"],
            }
            for key,value in sample_dict.items():
                if key=='sampled_positions':
                    continue
                new_dict[key] = value[:,layer,neuron].flatten().cpu().tolist()
            yield new_dict

if __name__=='__main__':
    parser = ArgumentParser()
    parser.add_argument('--model', default='OLMo-7B-0424-hf')
    parser.add_argument('--file', default='summary_refactored.pt')
    parser.add_argument('--push_to_hub', action='store_true',
                        help="Make sure to set the right HF_TOKEN first.")
    args = parser.parse_args()
    if 'summary' in args.file:
        name = 'neuron-activations'
    elif 'sample' in args.file:
        name = 'sampled-activations'
    else:
        raise NotImplementedError("File name (--file) should either contain 'summary' or 'sample'")
    root_path = (
        os.path.join(
            os.environ["WORK"],
            "GLUScope-results"
        )
        if "WORK" in os.environ
        else "./results"
    )
    model_path = os.path.join(
        root_path,
        args.model,
    )
    local_dataset_path=os.path.join(
        model_path,
        f'{name}_dataset'
    )

    if os.path.exists(local_dataset_path):
        dataset = datasets.load_from_disk(local_dataset_path)
    else:
        print('loading original dict...')
        my_dict = torch.load(os.path.join(model_path, args.file), map_location='cpu')
        if 'summary' in args.file:
            print('reformatting the dict...')
            if not any(key[1].startswith('blocks') for key in my_dict):
                new_dict = reformat_summary_old(my_dict)
            else:
                new_dict = reformat_summary(my_dict)
            print('converting to dataset...')
            dataset = datasets.Dataset.from_dict(new_dict)
        else:# 'sample' in args.file:
            print('converting to dataset (can take more than 15 minutes)...')
            dataset = datasets.Dataset.from_generator(
                sample_generator, gen_kwargs={"sample_dict":my_dict}
            )

    print("saving locally...")
    dataset.save_to_disk(local_dataset_path)
    if args.push_to_hub:
        print("pushing to hub...")
        username = whoami(token=os.environ['HF_TOKEN'])['name']
        print(username)
        login(token=os.environ['HF_TOKEN'])
        dataset.push_to_hub(f"{username}/{args.model}_{name}")
